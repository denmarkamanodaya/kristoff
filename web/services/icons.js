/**
 * Returns an inline SVG for a named icon (decorative: hidden from assistive tech).
 * @param name - A key of the icon map.
 * @param cls - Extra class names for the svg element.
 * @returns SVG markup, or an empty string for an unknown name.
 */
export function icon(name, cls = '') {
  const p = paths[name];
  return p ? `<svg class="ic${cls ? ` ${cls}` : ''}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${p}</svg>` : '';
}

/**
 * Replaces the content of every `[data-icon]` element under `root` with its icon.
 * @param root - Element or document to scan.
 */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => { el.innerHTML = icon(el.dataset.icon); });
}
